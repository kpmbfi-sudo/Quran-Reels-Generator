def get_comfort_hook(kind="surah", surah_num=None, ruqyah_id=None, custom_hook=None):
    """يرجع جملة راحة نفسية من 3 إلى 4 كلمات فقط."""
    if custom_hook and custom_hook.strip():
        words = custom_hook.strip().split()
        if len(words) <= 5:
            return " ".join(words[:4])
        return " ".join(words[:4])

    if kind == "surah" and surah_num:
        try:
            s_num = int(surah_num)
            if s_num in SURAH_COMFORT_HOOKS:
                return SURAH_COMFORT_HOOKS[s_num]
        except Exception:
            pass

    if kind == "ruqyah" and ruqyah_id:
        if ruqyah_id in RUQYAH_COMFORT_HOOKS:
            return RUQYAH_COMFORT_HOOKS[ruqyah_id]

    import random
    return random.choice(GENERAL_COMFORT_HOOKS)


def build_comfort_seo(title_prefix, comfort_hook, reciter_name, duration_seconds=0, surah_name=""):
    """يبني عنوان ووصف وكلمات دلالية متوافقة مع SEO والراحة النفسية."""
    hook = (comfort_hook or "أرح سمعك وقلبك").strip()
    
    # 1. عنوان جذاب تحت 95 حرف
    title = f"{title_prefix} | {reciter_name} 🌿 {hook}"
    if len(title) > 95:
        title = f"{title_prefix} | {reciter_name} 🌿"
    if len(title) > 95:
        title = f"{title_prefix} 🌿 {hook}"[:95]

    # 2. وصف منظم
    mins = int(duration_seconds // 60)
    secs = int(duration_seconds % 60)
    dur_str = f"{mins}:{secs:02d} دقيقة" if mins > 0 else f"{int(duration_seconds)} ثانية"

    description = f"""🌿 {hook} | تلاوة خاشعة وهادئة تريح النفس والبال
🎙️ القارئ: {reciter_name}
⏱️ المدة: {dur_str}

تلاوة قرآنية مباركة بجودة عالية، صدقة جارية لوجه الله تعالى.
استمع وتدبر في آيات الله لتنعم بالسكينة والطمأنينة وراحة القلب.
نسألكم صالح الدعاء بالمغفرة والرحمة لجميع موتى المسلمين. 🤲

قال رسول الله ﷺ: «خيركم من تعلم القرآن وعلمه»

#القرآن_الكريم #quran #راحة_نفسية #تلاوة_خاشعة #{hook.replace(' ', '_')} #صدقة_جارية"""

    # 3. كلمات دلالية قوية (Tags)
    tags = [
        hook,
        'راحة نفسية',
        'تلاوة خاشعة',
        'القرآن الكريم',
        'quran',
        reciter_name,
        'هدوء وسكينة',
        'قرآن للنوم',
        'أرح سمعك',
        'صدقة جارية'
    ]
    if surah_name:
        tags.insert(0, f"سورة {surah_name}")
        tags.insert(1, f"سورة {surah_name} كاملة")

    return {
        "title": title,
        "description": description,
        "tags": tags[:15],
        "hook": hook
    }
